const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const {spawn}=require('node:child_process');
const {tmpdir}=require('node:os');
const path=require('node:path');
// Real-browser acceptance: the owner writes notes on cases, sees them listed and deletes one.
(async()=>{
 const scratch=await fs.mkdtemp(path.join(tmpdir(),'owg-notes-'));
 const python=process.env.OWG_BROWSER_PYTHON||'python',base='http://127.0.0.1:8787';
 const axeSource=await fs.readFile(require.resolve('axe-core/axe.min.js'),'utf8');
 const server=spawn(python,['-m','uvicorn','process_logs_app:app','--app-dir','tests/browser','--host','127.0.0.1','--port','8787'],{
   env:{...process.env,OWG_BROWSER_TEST_DIR:scratch},stdio:['ignore','pipe','pipe']});
 let logs='',browser,spawnError;
 server.on('error',error=>{spawnError=error;});for(const pipe of [server.stdout,server.stderr])pipe.on('data',chunk=>{logs=(logs+chunk).slice(-8000);});
 try{
   let ready=false;for(let i=0;i<100;i++){
     if(spawnError)throw spawnError;if(server.exitCode!==null)throw new Error('Server exited: '+logs);
     try{await fs.access(path.join(scratch,'session.txt'));if((await fetch(base+'/')).ok){ready=true;break;}}catch{}
     await new Promise(resolve=>setTimeout(resolve,200));
   }if(!ready)throw new Error('Server not ready: '+logs);
   browser=await chromium.launch({...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{}),headless:true,args:['--no-sandbox']});
   const context=await browser.newContext();const page=await context.newPage(),errors=[];page.on('pageerror',error=>errors.push(error.message));
   const session=(await fs.readFile(path.join(scratch,'session.txt'),'utf8')).trim();
   await page.goto(base+'/#session='+session);await page.locator('[role=tab][data-tab=evidence]').click();
   const rows=['case,activity,time'];
   for(let i=0;i<6;i++)rows.push(`c${i},Receive,2024-03-0${1+i}T08:00:00Z`,`c${i},Pay,2024-03-0${1+i}T09:00:00Z`);
   await page.locator('#owgEventLogFile').setInputFiles({name:'orders.csv',mimeType:'text/csv',buffer:Buffer.from(rows.join('\n'))});
   await page.waitForFunction(()=>document.querySelector('#owgEventLogCase').options.length===3);
   await page.locator('#owgEventLogConsent').check();await page.locator('#owgEventLogImport').click();
   await page.locator('#owgEventLogStatus').filter({hasText:'Imported 12 events'}).waitFor();
   await page.locator('#owgEventLogAnalyze').click();
   const box=page.locator('#owgCaseNotes');await box.waitFor();await box.scrollIntoViewIfNeeded();
   await page.locator('#owgCaseNoteList').filter({hasText:'No case notes yet.'}).waitFor();
   await page.locator('#owgCaseNoteAdd').click();
   await page.locator('#owgCaseNoteStatus').filter({hasText:'Enter a case ID and a note.'}).waitFor();
   await page.locator('#owgCaseNoteCase').fill('nope');await page.locator('#owgCaseNoteText').fill('x');
   await page.locator('#owgCaseNoteAdd').click();
   await page.locator('#owgCaseNoteStatus').filter({hasText:'no case or object with this ID'}).waitFor();
   await page.locator('#owgCaseNoteCase').fill('c2');await page.locator('#owgCaseNoteText').fill('Customer called about the delay');
   await page.locator('#owgCaseNoteAdd').click();
   await page.locator('#owgCaseNoteStatus').filter({hasText:'Note added to case c2.'}).waitFor();
   await page.locator('#owgCaseNoteCase').fill('c4');await page.locator('#owgCaseNoteText').fill('Paid by card');
   await page.locator('#owgCaseNoteAdd').click();
   await page.locator('#owgCaseNoteList').filter({hasText:'2 notes on 2 cases.'}).waitFor();
   assert.equal(await page.locator('#owgCaseNoteText').inputValue(),'');
   await page.locator('#owgCaseNoteSearch').fill('called');await box.getByRole('button',{name:'Search notes',exact:true}).click();
   await page.locator('#owgCaseNoteList').filter({hasText:'1 note on 1 case.'}).waitFor();
   await box.getByRole('button',{name:'Open case c2',exact:true}).click();
   const evidence=page.locator('#owgEventLogCaseEvents');
   await evidence.getByRole('status').filter({hasText:'Showing 2 of 2 events'}).waitFor();
   const inline=page.locator('#owgEventLogCasesInlineNotes');
   await inline.locator('summary').click();
   await inline.getByText('Customer called about the delay',{exact:true}).waitFor();
   await inline.getByLabel('Note',{exact:true}).fill('Reviewed the timeline');
   await inline.getByRole('button',{name:'Add note',exact:true}).click();
   await inline.getByText('Reviewed the timeline',{exact:true}).waitFor();
   await box.getByRole('button',{name:'Clear search',exact:true}).click();
   await page.locator('#owgCaseNoteList').filter({hasText:'3 notes on 2 cases.'}).waitFor();
   await box.getByText('Reviewed the timeline',{exact:true}).waitFor();
   const noteRow=box.getByRole('row').filter({hasText:'Customer called about the delay'});
   await noteRow.getByRole('button',{name:'Edit note on case c2'}).click();
   await box.getByLabel('Edit note text for case c2').fill('Corrected finding');
   await box.getByRole('button',{name:'Cancel editing'}).click();
   await noteRow.getByText('Customer called about the delay',{exact:true}).waitFor();
   await noteRow.getByRole('button',{name:'Edit note on case c2'}).click();
   await box.getByLabel('Edit note text for case c2').fill('Corrected finding');
   const otherRow=inline.getByRole('row').filter({hasText:'Customer called about the delay'});
   await otherRow.getByRole('button',{name:'Edit note on case c2'}).click();
   await inline.getByLabel('Edit note text for case c2').fill('Other view correction');
   await inline.getByRole('button',{name:'Save note'}).click();
   await inline.getByText('Other view correction',{exact:true}).waitFor();
   assert.equal(await box.getByLabel('Edit note text for case c2').inputValue(),'Corrected finding');
   await box.getByRole('button',{name:'Save note'}).click();
   await box.getByText('This note changed since it was opened. Reload it before saving.').waitFor();
   assert.equal(await box.getByLabel('Edit note text for case c2').inputValue(),'Corrected finding');
   await box.getByRole('button',{name:'Cancel editing'}).click();
   const refreshed=box.getByRole('row').filter({hasText:'Other view correction'});
   await refreshed.getByRole('button',{name:'Edit note on case c2'}).click();
   await box.getByLabel('Edit note text for case c2').fill('Corrected finding');
   await box.getByRole('button',{name:'Save note'}).click();
   await box.getByText('Corrected finding',{exact:true}).waitFor();
   await inline.getByText('Corrected finding',{exact:true}).waitFor();
   await page.addScriptTag({content:axeSource});
   const audit=await page.evaluate(async()=>window.axe.run(document.querySelector('#owgCaseNotes'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}}));
   assert.deepEqual(audit.violations.map(v=>v.id+': '+v.nodes.map(n=>n.target).join(',')),[]);
   await box.getByRole('row').filter({hasText:'Corrected finding'}).getByRole('button',{name:'Delete note on case c2'}).click();
   await page.locator('#owgCaseNoteList').filter({hasText:'2 notes on 2 cases.'}).waitFor();
   await inline.getByText('Corrected finding',{exact:true}).waitFor({state:'detached'});
   assert.equal(await box.getByText('Corrected finding').count(),0);
   assert.deepEqual(errors,[]);
   console.log('Case notes browser acceptance passed: search, exact case history, inline notes, synchronized deletion, and WCAG audit.');
 }finally{if(browser)await browser.close();server.kill();}
})().catch(error=>{console.error(error);process.exit(1);});
