   await page.locator('#owgPredictSnapshots').getByText('No snapshots yet.').waitFor();
   await page.locator('#owgPredictEnds').fill('Close');
   const rank=page.locator('#owgPredictRank'),limit=page.locator('#owgPredictResultsLimit');
   assert.equal(await rank.locator('option[value="outcome"]').isDisabled(),true);
   await rank.selectOption('idle');await limit.selectOption('25');
   const prediction=page.locator('#owgPredictResults');
   const [ran]=await Promise.all([page.waitForResponse(r=>r.url().endsWith('/predictions?rank_by=idle')),
     page.locator('#owgPredictRun').click()]);
   assert.equal(ran.status(),200,await ran.text());assert.equal(ran.request().postDataJSON().limit,25);
   await prediction.getByText('Showing 6 of 6 estimates · Longest idle.',{exact:true}).waitFor();
   assert.equal(await prediction.getByRole('columnheader',{name:'Idle for',exact:true}).count(),1);
   const [json]=await Promise.all([page.waitForEvent('download'),page.locator('#owgPredictExportJson').click()]);
   const report=JSON.parse(await fs.readFile(await json.path(),'utf8'));
   assert.equal(report.ranked_by,'idle');assert.equal(report.predictions.length,6);
   assert.equal(report.predicted_open_cases,6);assert.equal(report.settings.limit,25);
   const [csv]=await Promise.all([page.waitForEvent('download'),page.locator('#owgPredictExportCsv').click()]);
   const sheet=await fs.readFile(await csv.path(),'utf8');
   assert.match(sheet,/Cases with comparable history,Estimates shown,Truncated/);
   assert.match(sheet,/completed_cases,idle,,6,6,6,false,o0/);
   const exact=page.locator('#owgPredictCaseKey');await exact.fill('o5');
   assert.equal(await rank.isDisabled(),true);assert.equal(await limit.isDisabled(),true);
   assert.equal(await prediction.textContent(),'');
   await page.locator('#owgPredictRun').click();
   await prediction.getByRole('cell',{name:'o5',exact:true}).waitFor();
   assert.equal(await prediction.locator('tbody tr').count(),1);
   await exact.fill('');
   await page.locator('#owgPredictSnapshot').click();
   await page.locator('#owgPredictSnapshotStatus').filter({hasText:'Saved a snapshot of 6 open cases.'}).waitFor();
   await page.getByRole('button',{name:/^Score snapshot from 2024-01-31T01:00/}).click();
   await page.locator('.owgSnapshotScore').getByText('No frozen case has finished yet').waitFor();
   // Freeze a capacity-matched prospective triage policy before newer events.
   const triage=page.locator('#owgTriagePolicyWorkbench');
   await triage.locator('summary').first().click();
   await page.locator('#owgTriageLoad').click();
   await page.waitForFunction(()=>document.querySelector('#owgTriageLog').options.length===2);
   await page.locator('#owgTriageLog').selectOption({index:1});
   await page.waitForFunction(()=>document.querySelector('#owgTriageSnapshot').options.length===2);
   await page.locator('#owgTriageSnapshot').selectOption({index:1});
   await page.locator('#owgTriageStatus').filter({hasText:'0 frozen policies'}).waitFor();
   await page.locator('#owgTriageLabel').fill('Review two cases');
   await page.locator('#owgTriageHours').fill('20');
   await page.locator('#owgTriageCapacity').fill('2');
   await page.locator('#owgTriageMinimum').fill('5');
   await page.locator('#owgTriagePreview').click();
   await page.locator('#owgTriagePreviewResult').getByText(/Capacity 2 per ranking/).waitFor();
   await page.locator('#owgTriageCapacity').fill('3');
   assert(await page.locator('#owgTriageFreeze').isDisabled());
   await page.locator('#owgTriageCapacity').fill('2');
   await page.locator('#owgTriagePreview').click();
   await page.locator('#owgTriagePreviewResult').getByText(/Capacity 2 per ranking/).waitFor();
   page.once('dialog',dialog=>dialog.accept());
   await page.locator('#owgTriageFreeze').click();
   await page.locator('#owgTriageStatus').filter({hasText:'Frozen policy saved'}).waitFor();
   await page.locator('#owgTriageScore').click();
   await page.locator('#owgTriageReport').getByText(/6 eligible cases · 0 known labels · 6 unknown labels/).waitFor();
   const newer=['case,activity,time',...[0,1,2,3].map(i=>`o${i},Close,${hour(day(30),11)}`),`o4,Close,${hour(day(30),41)}`,`x1,Receive,${hour(day(30),51)}`];
   await upload('newer.csv',newer.join('\n'),'#owgEventLogAppend');
   await page.locator('#owgEventLogStatus').filter({hasText:'Added 6 new events'}).waitFor();
   await page.locator('#owgEventLogAnalyze').click();
   await page.locator('#owgPredictSnapshots li').first().waitFor();
   await page.getByRole('button',{name:/^Score snapshot from 2024-01-31T01:00/}).click();
   const score=page.locator('.owgSnapshotScore');
   await score.getByText(/5 finished, 1 still open/).waitFor();
   const text=await score.textContent();
   assert.match(text,/Range covered 80\.0%/,text);
   assert.match(text,/1 still-open cases are already past their range/,text);
   assert.match(text,/lean towards short ones/,text);
   // The analysis panel may have been reconstructed after append; select the
   // exact local source again rather than relying on an old DOM selection.
   const laterTriage=page.locator('#owgTriagePolicyWorkbench');
   if(!(await laterTriage.locator('details').first().evaluate(n=>n.open)))
     await laterTriage.locator('summary').first().click();
   await page.locator('#owgTriageLoad').click();
   await page.waitForFunction(()=>document.querySelector('#owgTriageLog').options.length===2);
   if(!(await page.locator('#owgTriageLog').inputValue()))await page.locator('#owgTriageLog').selectOption({index:1});
   await page.waitForFunction(()=>document.querySelector('#owgTriageSnapshot').options.length===2);
   await page.locator('#owgTriageSnapshot').selectOption({index:1});
   await page.waitForFunction(()=>document.querySelector('#owgTriageSaved').options.length===2);
   await page.locator('#owgTriageSaved').selectOption({index:1});
   await page.locator('#owgTriageScore').click();
   await page.locator('#owgTriageReport').getByText(/6 eligible cases · 6 known labels · 0 unknown labels · 2 known positives/).waitFor();
   const [triageDownload]=await Promise.all([page.waitForEvent('download'),page.locator('#owgTriageExport').click()]);
   const triageReport=JSON.parse(await fs.readFile(await triageDownload.path(),'utf8'));
