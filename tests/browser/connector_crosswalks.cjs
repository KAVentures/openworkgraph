const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const {spawn}=require('node:child_process');
const os=require('node:os');
const path=require('node:path');
(async()=>{
 const scratch=await fs.mkdtemp(path.join(os.tmpdir(),'owg-crosswalk-browser-'));
 const port=process.env.OWG_BROWSER_TEST_PORT||'8791',base='http://127.0.0.1:'+port;
 const server=spawn(process.env.OWG_BROWSER_PYTHON||'python',['-m','uvicorn','connector_crosswalks_app:app','--app-dir','tests/browser','--host','127.0.0.1','--port',port],{env:{...process.env,OWG_BROWSER_TEST_DIR:scratch},stdio:['ignore','pipe','pipe']});
 let logs='',err,browser;server.on('error',e=>err=e);
 for(const stream of [server.stdout,server.stderr])stream.on('data',x=>logs=(logs+x).slice(-8000));
 try{
  let ready=false;
  for(let i=0;i<100;i++){if(err)throw err;if(server.exitCode!==null)throw Error(logs);try{if((await fetch(base+'/admin/connector-crosswalks')).ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,200));}
  assert.ok(ready,logs);
  browser=await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{})});
  const context=await browser.newContext({acceptDownloads:true});
  await context.addInitScript(()=>{sessionStorage.setItem('owg_admin_token','test-admin');sessionStorage.setItem('owg_admin_org','customer');});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',d=>d.accept());
  await page.goto(base+'/admin/connector-crosswalks');
  await page.locator('#saved').getByText('No active saved plans.').waitFor();
  await page.locator('#files').setInputFiles([path.join(scratch,'crosswalk1.json'),path.join(scratch,'crosswalk2.json')]);
  await page.locator('#fileReview table').nth(1).waitFor();
  assert.ok(await page.locator('#propose').isDisabled());
  await page.locator('#inspect').check();await page.locator('#tags').check();
  await page.locator('#propose').click();
  await page.locator('#status').filter({hasText:'Proposed 1 groups. None selected.'}).waitFor();
  assert.ok(await page.locator('#preview').isDisabled());
  assert.equal(await page.locator('#groups input').count(),1);
  assert.equal(await page.locator('#groups input').isChecked(),false);
  assert.equal(await page.locator('#files').inputValue(),'');
  await page.locator('#groups input').check();
  await page.locator('#preview').click();
  await page.locator('#reportPanel').waitFor({state:'visible'});
  assert.ok(await page.locator('#saveNew').isDisabled());
  assert.ok(await page.locator('#json').isDisabled());
  await page.locator('#assertions').check();await page.locator('#retain').check();
  await page.locator('#saveNew').click();
  await page.locator('#status').filter({hasText:'Saved revision 1.'}).waitFor();
  await page.locator('#saveRevision').click();
  await page.locator('#status').filter({hasText:'Saved revision 2.'}).waitFor();
  await page.getByRole('button',{name:'Open current review'}).click();
  await page.locator('#history').getByRole('button',{name:'Open revision 1'}).waitFor();
  assert.ok(await page.locator('#json').isDisabled());
  await page.locator('#history').getByRole('button',{name:'Open revision 1'}).click();
  await page.locator('#status').filter({hasText:'Saved revision reopened'}).waitFor();
  await page.locator('#assertions').check();await page.locator('#exportConfirm').check();
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#json').click()]);
  const result=JSON.parse(await fs.readFile(await download.path(),'utf8'));
  assert.equal(result.event_count,2);assert.equal(new Set(result.events.map(x=>x.case_id)).size,1);
  assert.equal(result.business_identity_independently_verified,false);
  assert.ok(!JSON.stringify(result).includes('e'.repeat(64)));
  await page.getByRole('button',{name:'Delete plan and history'}).click();
  await page.locator('#saved').getByText('No active saved plans.').waitFor();
  assert.ok(await page.locator('#json').isDisabled());
  await page.goto(base+'/admin/connector-case-review');
  await page.locator('#snapshots article').nth(1).waitFor();
  for(const item of await page.locator('#snapshots input').all())await item.check();
  await page.locator('#inspect').check();await page.locator('#open').click();
  await page.locator('#catalog article').nth(1).waitFor();
  for(const item of await page.locator('#catalog input').all())await item.check();
  await page.locator('#group').click();
  await page.locator('#groups article').waitFor();
  await page.locator('#preview').click();
  await page.locator('#temporalPanel').waitFor({state:'visible'});
  assert.ok(await page.locator('#temporalRun').isDisabled());
  await page.locator('#temporalConsent').check();await page.locator('#temporalRun').click();
  await page.locator('#temporalResult').getByText('Cross-case source-pair patterns',{exact:true}).waitFor();
  const [temporalDownload]=await Promise.all([page.waitForEvent('download'),page.locator('#temporalDownload').click()]);
  const temporal=JSON.parse(await fs.readFile(await temporalDownload.path(),'utf8'));
  assert.equal(temporal.summary.event_pairs,1);
  assert.equal(temporal.summary.equal_reported_points,1);
  assert.equal(temporal.summary.unaligned_events,0);
  assert.equal(temporal.source_pair_rollup[0].not_wholly_separated_groups,1);
  assert.equal(temporal.independently_verified_handoffs,false);
  await page.locator('#temporalConsent').uncheck();
  assert.ok(await page.locator('#temporalDownload').isDisabled());
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  assert.deepEqual(errors,[]);
  console.log('Crosswalk browser acceptance: explicit candidate review, exact plan revisions, export consent, deletion and mobile layout.');
 }finally{if(browser)await browser.close();server.kill('SIGTERM');await new Promise(resolve=>{if(server.exitCode!==null||err)resolve();else server.once('exit',resolve);});await fs.rm(scratch,{recursive:true,force:true});}
})().catch(e=>{console.error(e);process.exit(1);});
