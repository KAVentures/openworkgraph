"""The process in plain words: a short, deterministic summary of what the log shows.

Process mining tools increasingly open with a written summary (generated by an AI assistant in
Celonis and UiPath). This module writes one without a language model: each sentence is filled from
a computed figure, so it can be checked, and it links to the analysis that produced it. Nothing is
inferred beyond the numbers; sentences use cautious wording ("most cases", "stand out") and the
same caveats as the analyses they summarize.
"""
from __future__ import annotations

from typing import Any

from . import event_log_analytics as analytics
from . import event_log_insights as insights
from . import event_log_workspace as workspace
from .event_log_workspace import EventLogWorkspaceError

FORMAT = "openworkgraph.event_log_story.v1"


def _hours(seconds: float | None) -> str:
    if seconds is None:
        return "an unknown time"
    hours = seconds / 3600
    if hours < 1:
        return f"{max(1, round(seconds / 60))} minutes"
    if hours < 48:
        return f"{hours:.1f} hours".replace(".0 ", " ")
    return f"{hours / 24:.1f} days".replace(".0 ", " ")


def _pct(x: float | None) -> str:
    return "—" if x is None else f"{round(x * 100)}%"


def story(log_id: str, case_type: str | None = None, *, cohort: dict[str, Any] | None = None) -> dict[str, Any]:
    from . import event_log_alignments as alignments
    from . import event_log_model_quality as quality
    from . import event_log_pnml as pnml
    from . import event_log_unusual_cases as unusual
    summary = workspace.summary(log_id, case_type, cohort)
    cases = summary["cases"]
    if not cases:
        raise EventLogWorkspaceError("no cases in this selection")
    variants = workspace.variants(log_id, case_type, 3, cohort=cohort)
    kpis = analytics.kpis(log_id, case_type, None, None, cohort)
    found = insights.insights(log_id, {"limit": 3, **({"case_type": case_type} if case_type else {}),
                                       **({"cohort": cohort} if cohort else {})})
    sentences: list[dict[str, Any]] = []

    def say(text: str, section: str | None = None, **figures: Any) -> None:
        sentences.append({"text": text, "section": section, "figures": figures})

    dur = summary["case_duration_seconds"]
    say(f"The log has {cases:,} cases with {summary['events']:,} events across {summary['activities']} activities, "
        f"from {str(summary['first_event_at'])[:10]} to {str(summary['last_event_at'])[:10]}.", None,
        cases=cases, events=summary["events"], activities=summary["activities"])
    say(f"A typical case takes {_hours(dur['median'])} from its first to its last event; the slowest tenth take "
        f"more than {_hours(dur['p90'])}.", None, median_seconds=dur["median"], p90_seconds=dur["p90"])
    top = variants.get("variants") or []
    if top:
        share = top[0].get("share")
        if share is None and cases:
            share = top[0]["cases"] / cases
        say(f"The most common path ({' → '.join(top[0]['path'][:8])}{' …' if len(top[0]['path']) > 8 else ''}) is "
            f"followed by {_pct(share)} of cases; there are {variants.get('distinct_variants', len(top)):,} distinct "
            f"paths in all.", "owgPaths", top_share=share, distinct_paths=variants.get("distinct_variants"))
    rework = kpis.get("rework_rate")
    if rework:
        say(f"{_pct(rework)} of cases repeat at least one activity.", None, rework_rate=rework)
    try:
        q = quality.model_quality(log_id, case_type, levels="0,0.1,0.2,0.3", cohort=cohort)
        best = q.get("best_f_score_noise")
        if best is not None:
            xml, _ = pnml.discovered_pnml(log_id, case_type, noise=best, cohort=cohort)
            a = alignments.alignments(log_id, xml.encode(), case_type, cohort=cohort)
            f = a["fitness"]
            line = (f"Against the process model discovered from these cases, {_pct(f['fitting_case_share'])} of cases "
                    f"follow it exactly")
            skipped = a["model_moves"][:1]
            extra = a["log_moves"][:1]
            if skipped:
                line += f"; the step most often skipped is {skipped[0]['activity']} ({skipped[0]['cases']:,} cases)"
            if extra:
                line += (f"; the step most often done where the model does not expect it is {extra[0]['activity']} "
                         f"({extra[0]['cases']:,} cases)")
            say(line + ".", "owgPetri", fitting_case_share=f["fitting_case_share"], noise=best)
    except EventLogWorkspaceError:
        pass
    for finding in found.get("findings", [])[:2]:
        say(f"Where to look: {finding['title'].rstrip('.')}.", "owgEventLogInsights",
            kind=finding.get("kind"), case_share=finding.get("case_share"))
    try:
        u = unusual.unusual_cases(log_id, case_type, limit=1, include_case_ids=False, cohort=cohort)
        if u["unusual_cases"]:
            phrase = {"rare_path": "a rare path", "unusually_slow": "being unusually slow",
                      "unusually_fast": "being unusually fast", "unusually_long": "having unusually many events",
                      "heavy_rework": "heavy rework", "rare_activity": "a rare activity"}
            reasons = " or ".join(phrase.get(k, k.replace("_", " ")) for k in list(u["by_signal"])[:2])
            say(f"{u['unusual_cases']:,} cases ({_pct(u['unusual_share'])}) stand out, mostly for {reasons}.",
                "owgUnusual", unusual_cases=u["unusual_cases"])
    except EventLogWorkspaceError:
        pass
    return {
        "format": FORMAT, "log_id": log_id, "case_notion": summary.get("case_notion"),
        "cases": cases, "sentences": sentences,
        "text": " ".join(s["text"] for s in sentences),
        "method": "each sentence is filled from a computed figure of this log; no language model is used",
        "caveat": ("A summary of recorded events, not a diagnosis. Durations are first to last recorded event; the model "
                   "is a draft discovered from these cases; unusual is not wrong."),
    }


__all__ = ["story", "FORMAT"]
